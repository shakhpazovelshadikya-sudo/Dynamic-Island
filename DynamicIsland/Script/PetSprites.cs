    public const int Size = 12;

    public static readonly string[] FrameKeys = { "sit0", "sit1", "sit2", "walk0", "walk1", "sleep0", "sleep1", "jump", "dance0", "dance1" };

    public static PetDef? Find(string? id) => All.FirstOrDefault(p => p.Id == id);

    /// <summary>Проверка спрайтов: все кадры на месте, размер 12×12, у каждого символа есть цвет.</summary>
    public static string? Validate(PetDef p)
    {
        foreach (var key in FrameKeys)
        {
            if (!p.Frames.TryGetValue(key, out var rows)) return $"{p.Id}: нет кадра {key}";
            if (rows.Length != Size) return $"{p.Id}/{key}: {rows.Length} строк вместо {Size}";
            foreach (var row in rows)
            {
                if (row.Length != Size) return $"{p.Id}/{key}: строка «{row}» не {Size} символов";
                foreach (char c in row)
                    if (c != '.' && !p.Palette.ContainsKey(c)) return $"{p.Id}/{key}: нет цвета для «{c}»";
            }
        }
        return null;
    }

    private static readonly Dictionary<(string, string), BitmapSource> Cache = new();

    /// <summary>Кадр как картинка 12×12 (в окне растягивается без сглаживания — пиксели остаются чёткими).</summary>
    public static BitmapSource GetFrame(PetDef pet, string key)
    {
        if (Cache.TryGetValue((pet.Id, key), out var cached)) return cached;

        var rows = pet.Frames[key];
        var px = new byte[Size * Size * 4];
        for (int y = 0; y < Size; y++)
            for (int x = 0; x < Size; x++)
            {
                char c = rows[y][x];
                if (c == '.') continue;
                uint v = pet.Palette[c];
                int i = (y * Size + x) * 4;
                px[i] = (byte)(v & 0xFF);            // B
                px[i + 1] = (byte)((v >> 8) & 0xFF); // G
                px[i + 2] = (byte)((v >> 16) & 0xFF); // R
                px[i + 3] = 255;
            }

        var bmp = BitmapSource.Create(Size, Size, 96, 96, PixelFormats.Bgra32, null, px, Size * 4);
        bmp.Freeze();
        Cache[(pet.Id, key)] = bmp;
        return bmp;
    }

