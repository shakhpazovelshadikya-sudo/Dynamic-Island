/// <summary>Один питомец: имя, палитра и кадры анимации (пиксель-арт 12×12; '.' — прозрачный пиксель).</summary>
public sealed record PetDef(string Id, string Title, IReadOnlyDictionary<char, uint> Palette, IReadOnlyDictionary<string, string[]> Frames);

/// <summary>
/// Питомцы пилюли. Кадры (ключи в <see cref="FrameKeys"/>):
/// sit0 — сидит, sit1 — моргает, sit2 — виляет хвостом, walk0/walk1 — шаг, sleep0/sleep1 — спит,
/// jump — прыжок, dance0/dance1 — пританцовывает под музыку.
/// Чтобы добавить своего питомца — допиши запись в <see cref="All"/> (палитра + все кадры) и перезапусти тесты: они проверят размеры и цвета.
